"""Generates supabase/seed.sql from questions_data.py. Usage: python3 tools/build_seed.py"""
import json, uuid, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from questions_data import Q, CATS
NS = uuid.UUID("6f1c2d7e-9b1a-4c55-8a39-0cd0de7ec71e")
def u(*p): return str(uuid.uuid5(NS, "/".join(map(str, p))))
def lit(s): return "'" + s.replace("'", "''") + "'"
def js(o): return lit(json.dumps(o, ensure_ascii=False)) + "::jsonb"
assert len(Q) == 20, "need exactly 20 questions"
out = ["-- GENERATED by tools/build_seed.py - do not edit by hand.", "begin;"]
for slug, (en, ar) in CATS.items():
    out.append(f"insert into public.categories(id,slug,name) values ({lit(u('cat',slug))},{lit(slug)},{js({'en':en,'ar':ar})}) on conflict (id) do update set name=excluded.name;")
counts = [0]*4
for n, (stage, cat, ci, en, ar) in enumerate(Q, 1):
    assert len(en[1]) == len(ar[1]) == 4 and len(en[4]) == len(ar[4]) == 4, n
    assert en[4][ci] == "" and ar[4][ci] == "" and sum(1 for x in en[4] if x) == 3 and sum(1 for x in ar[4] if x) == 3, n
    assert cat in CATS, n
    qid = u("q", n); counts[ci] += 1
    out.append(f"insert into public.questions(id,position,stage,category_id,scenario) values ({lit(qid)},{n},{stage},{lit(u('cat',cat))},{js({'en':en[0],'ar':ar[0]})}) on conflict (id) do update set scenario=excluded.scenario, stage=excluded.stage, category_id=excluded.category_id;")
    for p in range(4):
        out.append(f"insert into public.options(id,question_id,position,label) values ({lit(u('o',n,p))},{lit(qid)},{p},{js({'en':en[1][p],'ar':ar[1][p]})}) on conflict (id) do update set label=excluded.label;")
    fb = {l: {"threat": d[2], "lesson": d[3], "wrong": d[4]} for l, d in (("en", en), ("ar", ar))}
    out.append(f"insert into public.answer_keys(question_id,correct_option_id,feedback) values ({lit(qid)},{lit(u('o',n,ci))},{js(fb)}) on conflict (question_id) do update set correct_option_id=excluded.correct_option_id, feedback=excluded.feedback;")
    lens = [len(x) for x in en[1]]
    print(n, stage, cat, "correct", "ABCD"[ci], lens, "<-- correct is longest" if lens[ci] == max(lens) else "")
out.append("commit;")
(pathlib.Path(__file__).parent.parent / "supabase" / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print("answer position counts A-D:", counts)
